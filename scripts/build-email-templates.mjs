import mjml2html from 'mjml';
import { readFileSync, writeFileSync } from 'node:fs';
const src = process.argv[2], out = process.argv[3];
const out_ = {};
for (const name of ['NewInquiry', 'InquiryReceived']) {
  const text = readFileSync(`${src}/${name}.html`, 'utf8');
  const { html, errors } = mjml2html(text, { validationLevel: 'soft' });
  if (errors.length) console.error(name, errors.map((e) => e.formattedMessage));
  const subject = (text.match(/<mj-title>([\s\S]*?)<\/mj-title>/) || [])[1]?.trim() || 'Coinexa.net';
  out_[name] = { subject, html };
}
writeFileSync(out, `// GENERATED by scripts/build-email-templates.mjs from base44/emails/*.html (MJML). Do not edit.\nexport const TEMPLATES: Record<string, { subject: string; html: string }> = ${JSON.stringify(out_, null, 1)};\n`);
console.log(Object.fromEntries(Object.entries(out_).map(([k, v]) => [k, [v.subject, v.html.length]])));
